#!/usr/bin/env node
/**
 * Writes the design tokens from DESIGN.md's front matter. The UI takes its colour,
 * spacing, type and radius values only from these generated tokens.
 *
 *   node scripts/build-tokens.mjs           writes src/shared/theme/tokens.css and tokens.ts
 *   node scripts/build-tokens.mjs --check   writes nothing; exits 1 if either file is stale
 *
 * Both modes first check every colour pair the components use, in both themes, and stop
 * with the failing pairs listed if one misses its WCAG 2.2 AA minimum:
 * 4.5:1 for text, 3:1 for control edges, focus rings and graph marks.
 *
 * Needs Node 22.18 or later: the contrast maths is imported from the UI's own TypeScript
 * module through Node's type stripping, so the build and the UI share one implementation.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import process from "node:process";

import { MIN_CONTRAST_NON_TEXT, MIN_CONTRAST_TEXT, contrastRatio } from "../src/shared/theme/contrast.ts";

const DESIGN_PATH = fileURLToPath(new URL("../../DESIGN.md", import.meta.url));
const CSS_PATH = fileURLToPath(new URL("../src/shared/theme/tokens.css", import.meta.url));
const TS_PATH = fileURLToPath(new URL("../src/shared/theme/tokens.ts", import.meta.url));

const ROOT_FONT_SIZE_PX = 16;
const REM_DECIMALS = 4;
const THEMES = /** @type {const} */ (["light", "dark"]);
// The front-matter group that holds each theme's colours.
const COLOUR_GROUP = { light: "colors", dark: "colors-dark" };
// Groups whose px lengths are written in rem, so they follow the reader's font size.
const REM_GROUPS = new Set(["spacing", "sizes"]);
const PX_LENGTH = /(-?\d*\.?\d+)px\b/g;
const DURATION = /^\d*\.?\d+m?s$/;

const HEADER =
  "Generated by crawler-ui/scripts/build-tokens.mjs from DESIGN.md. Do not edit: change DESIGN.md and run the script.";

/**
 * Every pairing a shared component draws, as [foreground, background, minimum, where].
 * A component that puts a colour on a new ground adds its pair here in the same commit.
 */
const CONTRAST_PAIRS = [
  ["ink", "paper", MIN_CONTRAST_TEXT, "primary text, focus ring"],
  ["ink", "sheet", MIN_CONTRAST_TEXT, "primary text on raised surfaces, field text"],
  ["ink-2", "paper", MIN_CONTRAST_TEXT, "body text"],
  ["ink-2", "sheet", MIN_CONTRAST_TEXT, "body text on raised surfaces"],
  ["muted", "paper", MIN_CONTRAST_TEXT, "captions, hints, placeholders"],
  ["muted", "sheet", MIN_CONTRAST_TEXT, "captions on raised surfaces, table headers"],
  ["vermilion", "paper", MIN_CONTRAST_TEXT, "score figure"],
  ["vermilion", "sheet", MIN_CONTRAST_TEXT, "score figure on raised surfaces"],
  ["plum-error", "paper", MIN_CONTRAST_TEXT, "error text"],
  ["plum-error", "sheet", MIN_CONTRAST_TEXT, "error text in a toast or field"],
  ["on-ink", "ink", MIN_CONTRAST_TEXT, "pressed button, primary button"],
  ["on-ink", "ink-2", MIN_CONTRAST_TEXT, "primary button on hover"],
  ["ink", "row-rule", MIN_CONTRAST_TEXT, "outline button on hover"],
  ["on-plum", "plum-error", MIN_CONTRAST_TEXT, "armed confirm button"],
  ["ink", "rule", MIN_CONTRAST_TEXT, "state chip"],
  ["control", "paper", MIN_CONTRAST_NON_TEXT, "control edges"],
  ["control", "sheet", MIN_CONTRAST_NON_TEXT, "control edges on raised surfaces"],
  ["edge", "paper", MIN_CONTRAST_NON_TEXT, "graph edges"],
  ["stage-created-stroke", "paper", MIN_CONTRAST_NON_TEXT, "found page outline"],
  ["stage-fetched-stroke", "paper", MIN_CONTRAST_NON_TEXT, "fetched page outline"],
  ["stage-filtered-stroke", "paper", MIN_CONTRAST_NON_TEXT, "filtered page outline"],
  ["stage-scored-stroke", "paper", MIN_CONTRAST_NON_TEXT, "scored page outline"],
  ["stage-expanded-stroke", "paper", MIN_CONTRAST_NON_TEXT, "expanded page outline"],
];

// ---------------------------------------------------------------------------------------------
// Front matter: the YAML subset DESIGN.md uses (nested maps of scalars, two-space indent).

/** A quoted or bare YAML scalar as a string or number. */
function parseScalar(raw) {
  const text = raw.trim();
  if (text.startsWith('"')) return JSON.parse(text);
  if (text.startsWith("'") && text.endsWith("'")) return text.slice(1, -1).replaceAll("''", "'");
  if (/^-?\d+(\.\d+)?$/.test(text)) return Number(text);
  return text;
}

/** The front matter between the first two `---` lines, as nested objects. */
export function parseFrontMatter(markdown) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(markdown.replaceAll("\r\n", "\n"));
  if (!match) throw new Error("DESIGN.md has no front matter between two --- lines.");
  const root = {};
  const stack = [{ indent: -1, node: root }];
  match[1].split("\n").forEach((line, index) => {
    const content = line.trim();
    if (content === "" || content.startsWith("#")) return;
    const entry = /^([A-Za-z0-9_-]+):(?:\s+(.*))?$/.exec(content);
    if (!entry) {
      throw new Error(`DESIGN.md line ${index + 2}: the token build reads only "key: value" maps, got "${content}".`);
    }
    const indent = line.length - line.trimStart().length;
    while (stack[stack.length - 1].indent >= indent) stack.pop();
    const parent = stack[stack.length - 1].node;
    const [, key, value] = entry;
    if (value === undefined || value === "") {
      const child = {};
      parent[key] = child;
      stack.push({ indent, node: child });
    } else {
      parent[key] = parseScalar(value);
    }
  });
  return root;
}

// ---------------------------------------------------------------------------------------------
// Values

function toRem(px) {
  return `${Number((px / ROOT_FONT_SIZE_PX).toFixed(REM_DECIMALS))}rem`;
}

/** Every px length in a value as rem: "clamp(40px, 5.6vw, 76px)" becomes "clamp(2.5rem, 5.6vw, 4.75rem)". */
function pxToRem(value) {
  return String(value).replace(PX_LENGTH, (_, px) => toRem(Number(px)));
}

/** Lower case, and the short form when every pair repeats (#ffffff to #fff), as stylelint wants. */
function normaliseHex(colour) {
  const hex = String(colour).toLowerCase();
  const pairs = /^#([0-9a-f]{6}|[0-9a-f]{8})$/.test(hex) ? hex.slice(1).match(/../g) : null;
  if (pairs && pairs.every((pair) => pair[0] === pair[1])) return `#${pairs.map((pair) => pair[0]).join("")}`;
  return hex;
}

const GENERIC_FONT_FAMILIES = new Set([
  "serif",
  "sans-serif",
  "monospace",
  "cursive",
  "fantasy",
  "math",
  "emoji",
  "fangsong",
  "system-ui",
  "ui-serif",
  "ui-sans-serif",
  "ui-monospace",
  "ui-rounded",
]);

/**
 * A font stack with every named family in double quotes and generic families bare. In a
 * custom property stylelint reads `Georgia` as a keyword that should be lower case, so names
 * are quoted rather than left to the `font-family` exemption.
 */
function normaliseFontFamily(stack) {
  return String(stack)
    .split(",")
    .map((family) => family.trim().replace(/^["']|["']$/g, ""))
    .map((family) => (GENERIC_FONT_FAMILIES.has(family) ? family : `"${family}"`))
    .join(", ");
}

function camelCase(name) {
  return name.replace(/-([a-z0-9])/g, (_, next) => next.toUpperCase());
}

const TYPE_PROPERTIES = {
  fontFamily: { suffix: "family", convert: normaliseFontFamily },
  fontSize: { suffix: "size", convert: pxToRem },
  fontWeight: { suffix: "weight", convert: String },
  lineHeight: { suffix: "line-height", convert: String },
  letterSpacing: { suffix: "letter-spacing", convert: String },
  fontFeature: { suffix: "numeric", convert: String },
};

function requireGroup(design, name) {
  const group = design[name];
  if (!group || typeof group !== "object") throw new Error(`DESIGN.md front matter has no "${name}" group.`);
  return group;
}

/** The token model the two writers share. */
export function buildModel(design) {
  const colours = {};
  for (const theme of THEMES) {
    colours[theme] = Object.fromEntries(
      Object.entries(requireGroup(design, COLOUR_GROUP[theme])).map(([name, value]) => [name, normaliseHex(value)]),
    );
  }
  const lightNames = Object.keys(colours.light).sort();
  const darkNames = Object.keys(colours.dark).sort();
  const missing = lightNames.filter((name) => !darkNames.includes(name));
  const extra = darkNames.filter((name) => !lightNames.includes(name));
  if (missing.length || extra.length) {
    throw new Error(
      `"colors" and "colors-dark" must name the same tokens. Missing in colors-dark: ${missing.join(", ") || "none"}. ` +
        `Only in colors-dark: ${extra.join(", ") || "none"}.`,
    );
  }

  const scales = {};
  for (const [group, prefix] of [
    ["spacing", "space"],
    ["rounded", "radius"],
    ["sizes", "size"],
    ["strokes", "stroke"],
    ["motion", "motion"],
    ["layers", "layer"],
  ]) {
    scales[prefix] = Object.fromEntries(
      Object.entries(requireGroup(design, group)).map(([name, value]) => [
        name,
        REM_GROUPS.has(group) ? pxToRem(value) : value,
      ]),
    );
  }

  const typography = {};
  for (const [role, spec] of Object.entries(requireGroup(design, "typography"))) {
    typography[role] = {};
    for (const [property, value] of Object.entries(spec)) {
      const known = TYPE_PROPERTIES[property];
      if (!known) throw new Error(`DESIGN.md typography.${role}.${property} is not a property the token build knows.`);
      typography[role][known.suffix] = known.convert(value);
    }
  }
  return { colours, scales, typography };
}

// ---------------------------------------------------------------------------------------------
// Contrast

/** Every pair below its minimum, in either theme, as readable lines. */
export function findContrastFailures(colours) {
  const failures = [];
  for (const theme of THEMES) {
    for (const [foreground, background, minimum, where] of CONTRAST_PAIRS) {
      const fg = colours[theme][foreground];
      const bg = colours[theme][background];
      if (fg === undefined || bg === undefined) {
        failures.push(`${theme}: ${foreground} on ${background} names a colour DESIGN.md does not define (${where})`);
        continue;
      }
      const ratio = contrastRatio(fg, bg);
      if (ratio < minimum) {
        failures.push(
          `${theme}: ${foreground} ${fg} on ${background} ${bg} is ${ratio.toFixed(2)}:1, needs ${minimum}:1 (${where})`,
        );
      }
    }
  }
  return failures;
}

// ---------------------------------------------------------------------------------------------
// Writers

function declarations(entries, indent = "  ") {
  return entries.map(([name, value]) => `${indent}--${name}: ${value};`).join("\n");
}

function colourDeclarations(colours, indent) {
  return declarations(
    Object.entries(colours).map(([name, value]) => [`color-${name}`, value]),
    indent,
  );
}

export function renderCss({ colours, scales, typography }) {
  const scaleBlocks = Object.entries(scales).map(
    ([prefix, values]) =>
      `  /* ${prefix} */\n` + declarations(Object.entries(values).map(([name, value]) => [`${prefix}-${name}`, value])),
  );
  const typeBlock =
    "  /* type */\n" +
    declarations(
      Object.entries(typography).flatMap(([role, properties]) =>
        Object.entries(properties).map(([suffix, value]) => [`type-${role}-${suffix}`, value]),
      ),
    );
  const stillMotion = Object.entries(scales.motion)
    .filter(([, value]) => DURATION.test(String(value)))
    .map(([name]) => [`motion-${name}`, "0ms"]);

  return `/* ${HEADER} */

/* Theme-independent tokens. */
:root {
${[...scaleBlocks, typeBlock].join("\n\n")}
}

/* Light plate: the default, for data-theme absent, "light", or "system" on a light system. */
:root {
  color-scheme: light;

${colourDeclarations(colours.light, "  ")}
}

/* Night plate, chosen by the reader. */
:root[data-theme="dark"] {
  color-scheme: dark;

${colourDeclarations(colours.dark, "  ")}
}

/* Night plate, following the system when the reader chose "system". */
@media (prefers-color-scheme: dark) {
  :root[data-theme="system"] {
    color-scheme: dark;

${colourDeclarations(colours.dark, "    ")}
  }
}

/* Reduced motion: every duration token becomes instant, so components honour it by default. */
@media (prefers-reduced-motion: reduce) {
  :root {
${declarations(stillMotion, "    ")}
  }
}
`;
}

/** A TypeScript literal in the quotes Prettier keeps: single quotes when the text holds double ones. */
function tsLiteral(value) {
  if (typeof value === "number") return String(value);
  const text = String(value);
  return text.includes('"') && !text.includes("'") ? `'${text}'` : JSON.stringify(text);
}

function tsObject(entries, indent) {
  const inner = `${indent}  `;
  return `{\n${entries.map(([key, value]) => `${inner}${key}: ${value},`).join("\n")}\n${indent}}`;
}

function tsFlatObject(values, indent = "") {
  return tsObject(
    Object.entries(values).map(([name, value]) => [camelCase(name), tsLiteral(value)]),
    indent,
  );
}

export function renderTs({ colours, scales, typography }) {
  const colourObject = tsObject(
    THEMES.map((theme) => [theme, tsFlatObject(colours[theme], "  ")]),
    "",
  );
  const colourVars = tsObject(
    Object.keys(colours.light).map((name) => [camelCase(name), JSON.stringify(`var(--color-${name})`)]),
    "",
  );
  const typeObject = tsObject(
    Object.entries(typography).map(([role, properties]) => [camelCase(role), tsFlatObject(properties, "  ")]),
    "",
  );
  const scaleExports = [
    ["space", "Spacing steps, in rem."],
    ["radius", "Corner radii."],
    ["size", "Fixed sizes, in rem: target sizes, control heights, the panel width, the reading measure."],
    ["stroke", "Line widths, in px so hairlines stay one device-independent pixel."],
    ["motion", "Durations and easing. The CSS variables drop to 0ms under reduced motion; these values do not."],
    ["layer", "Stacking order (z-index) for layers above the page."],
  ].map(([name, doc]) => `/** ${doc} */\nexport const ${name} = ${tsFlatObject(scales[name])} as const;\n`);

  return `// ${HEADER}

/** The two plates: light (paper) and dark (night). */
export const THEME_NAMES = ["light", "dark"] as const;
export type ThemeName = (typeof THEME_NAMES)[number];

/** Colour values per theme, for drawing on a canvas or in SVG attributes, where CSS variables do not reach. */
export const colors = ${colourObject} as const;

export type ColorToken = keyof (typeof colors)["light"];

/** The CSS variable for each colour, for a data-driven inline style that must still follow the theme. */
export const colorVar = ${colourVars} as const satisfies Record<ColorToken, string>;

${scaleExports.join("\n")}
/** Type roles: family, size (rem), weight and, where set, line height, letter spacing and numerals. */
export const typography = ${typeObject} as const;
`;
}

// ---------------------------------------------------------------------------------------------

async function main() {
  const check = process.argv.includes("--check");
  const model = buildModel(parseFrontMatter(await readFile(DESIGN_PATH, "utf8")));

  const failures = findContrastFailures(model.colours);
  if (failures.length) {
    console.error(`Contrast check failed for ${failures.length} pair(s); no tokens were written:`);
    for (const failure of failures) console.error(`  ${failure}`);
    console.error("Change the colour in DESIGN.md, or the pairing in the component, and run the script again.");
    process.exit(1);
  }

  const outputs = [
    [CSS_PATH, renderCss(model)],
    [TS_PATH, renderTs(model)],
  ];
  if (check) {
    const stale = [];
    for (const [path, content] of outputs) {
      const current = await readFile(path, "utf8").catch(() => null);
      if (current !== content) stale.push(path);
    }
    if (stale.length) {
      console.error(`Tokens are out of date with DESIGN.md: ${stale.join(", ")}. Run node scripts/build-tokens.mjs.`);
      process.exit(1);
    }
    console.log(`Tokens match DESIGN.md; ${CONTRAST_PAIRS.length} pairs pass in both themes.`);
    return;
  }
  for (const [path, content] of outputs) await writeFile(path, content);
  console.log(`Wrote ${CSS_PATH} and ${TS_PATH}; ${CONTRAST_PAIRS.length} pairs pass in both themes.`);
}

// Run only as a script, so the parser and renderers can be imported by a test.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
